/// TXT 目录（章节标题行）规则。
///
/// 规则是一组正则，从全文里"认"出章节标题行。判定标准只有一条：
/// **同一套规则在整本书里命中次数最多者胜出**（原版 `TextFile.getTocRule` 的做法）。
/// 不要改成"任一规则命中就收录"——`1.` `书名 一` 这类宽松规则会把正文短行
/// 全变成章节，目录直接炸成几千条。
///
/// 规则文本是 Java 正则，依赖环视（`(?<=`）、惰性量词（`+?`）。
/// Dart 的 `RegExp` 用 V8 的 Irregexp，环视是支持的；若哪天要移植到别的运行时，
/// 这是第一个会挂的地方。
library;

/// 一条目录规则。
class TxtTocRule {
  const TxtTocRule(this.name, this.pattern, {this.titleTemplate});

  /// 便于日志与调试的名字（原版 UI 里也显示这个）。
  final String name;

  /// 正则本体，按**多行模式**编译（`^`/`$` 对齐行首行尾）。
  final String pattern;

  /// 标题模板，支持 `$1`/`$2` 引用捕获组。
  ///
  /// 原版没这个能力（标题永远取 `matcher.group()`），但用户自定义规则时
  /// "只取标题、丢掉章号"是高频需求，所以这里放开：
  /// 模板为 null 时行为与原版一致。
  final String? titleTemplate;

  /// 解析用户传入的规则字符串。
  ///
  /// 允许两种写法：
  /// - `^第(\\d+)章(.*)$`：纯正则；
  /// - `^第(\\d+)章(.*)$\t第$1章$2`：正则 + TAB + 标题模板。
  ///
  /// 用 TAB 而不是别的分隔符，是因为正则里 `|` `:` `~` 都可能出现，
  /// 而 TAB 在正则中没有语义（只能写成 `\t`），冲突面最小。
  factory TxtTocRule.parse(String raw, {int index = 0}) {
    final tab = raw.indexOf('\t');
    if (tab > 0) {
      return TxtTocRule(
        '用户规则${index + 1}',
        raw.substring(0, tab),
        titleTemplate: raw.substring(tab + 1),
      );
    }
    return TxtTocRule('用户规则${index + 1}', raw);
  }

  RegExp compile() => RegExp(pattern, multiLine: true);

  @override
  String toString() => 'TxtTocRule($name)';
}

/// 内置规则集，顺序 = 优先级（命中数相同时取靠前的）。
///
/// 内容来自 legado `assets/defaultData/txtTocRule.json` 中 `enable=true` 的条目，
/// 另外补了三条中文网文里常见、原版靠"用户自建规则"覆盖的写法：
/// `Chapter 12`、`【第一章】`、`1.标题`。
const defaultTxtTocRules = <TxtTocRule>[
  // 1. 【第一章 标题】/〔第1章〕—— 方括号包裹，噪声最低，优先
  TxtTocRule(
    '特殊符号包裹的章号',
    r'^[ 　\t]{0,6}[【〔〖「『〈［\[(（]\s*(?:第\s{0,4}[\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,10}\s{0,4}[章节回卷集部篇]|[Cc]hapter\s*\d{1,4}).{0,26}$',
  ),
  // 2. 标准写法：第一章 标题（行首，允许缩进）
  TxtTocRule(
    '目录',
    r'^[ 　\t]{0,4}(?:序章|楔子|正文(?!完|结)|终章|后记|尾声|番外|第\s{0,4}[\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]+?\s{0,4}(?:章|节(?!课)|卷|集(?![合和])|部(?![分赛游])|篇(?!张))).{0,30}$',
  ),
  // 3. 同上，但标题行前可能还有别的内容（靠前一个空白定位）
  TxtTocRule(
    '目录(去空白)',
    r'(?<=[　\s])(?:序章|楔子|正文(?!完|结)|终章|后记|尾声|番外|第\s{0,4}[\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]+?\s{0,4}(?:章|节(?!课)|卷|集(?![合和]))).{0,30}$',
  ),
  // 4. 回/话/场：古典与轻小说常用
  TxtTocRule(
    '目录(古典、轻小说)',
    r'^[ 　\t]{0,4}(?:序章|楔子|正文(?!完|结)|终章|后记|尾声|番外|第\s{0,4}[\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]+?\s{0,4}(?:章|节(?!课)|卷|集(?![合和])|部(?![分赛游])|回(?![合来事去])|场(?![和合比电是])|话|篇(?!张))).{0,30}$',
  ),
  // 5. 英文章节：Chapter 12 / Section 3 / Part II
  TxtTocRule(
    'English chapter',
    r'^[ 　\t]{0,4}(?:[Cc]hapter|[Ss]ection|[Pp]art|[Ee]pisode|[Bb]ook)\s{0,4}[\dIVXLCivxlc]{1,8}\b.{0,30}$',
  ),
  // 6. 纯数字 + 分隔符 + 标题：1、标题 / 12. 标题 / 3．标题
  TxtTocRule(
    '数字 分隔符 标题',
    r'^[ 　\t]{0,4}\d{1,5}\s{0,2}[:：,.，、．·_—\-]\s*\S.{0,26}$',
  ),
  // 7. 中文数字 + 分隔符 + 标题：一、标题 / 二十四章 标题
  TxtTocRule(
    '大写数字 分隔符 标题',
    r'^[ 　\t]{0,4}(?:[零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8}章?|序章|楔子|终章|后记|尾声|番外)[ 、_—\-：:].{1,28}$',
  ),
  // 8. 正文/简介/序 之类不带编号的固定标题
  TxtTocRule(
    '正文与前言',
    r'^[ 　\t]{0,4}(?:正文|(?:内容|文章)?简介|文案|前言|序言|序|自序|引子|楔子|终章|后记|尾声|番外)[ 　\t]{0,4}.{0,20}$',
  ),
  // 9. 卷/章 序号 标题：卷三 风起
  TxtTocRule(
    '卷章 序号 标题',
    r'^[ 　\t]{0,4}[卷章部篇]\s{0,2}[\d零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8}.{0,28}$',
  ),
  // 10. 书名（一）/ 书名 一
  TxtTocRule(
    '书名 括号序号',
    r'^[一-龥]{1,20}[ 　\t]{0,4}[(（][\d〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]{1,8}[)）][ 　\t]{0,4}$',
  ),
  // 11. 分页/分节阅读（盗版站导出常见）
  TxtTocRule(
    '分页分节阅读',
    r'(?<=[ 　\t]{0,4})(?:.{0,15}分[页节章段]阅读[-_ ]|第\s{0,4}[\d零一二两三四五六七八九十百千万]{1,6}\s{0,4}[页节]).{0,30}$',
  ),
];
